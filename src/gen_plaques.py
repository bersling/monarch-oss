"""Gallery plaques: data/gallery.json -> PNG textures + plaque boards + Pset_Gallery props.

    uv run python src/gen_plaques.py            regenerate assets/plaques/*.png and the data entries
    uv run python src/gen_plaques.py --check    exit 1 if the data entries are out of date

For every exhibit in data/gallery.json this script
  1. renders a 600 x 400 px plaque (PyMuPDF: dark board, bold title, provenance and licence,
     "Ask your agent:" with the prompt in a mono font) into assets/plaques/<key>.png,
  2. upserts the plaque board as furniture GAL_PLAQUE_<KEY> in the gallery's storey JSON:
     a 0.30 x 0.02 x 0.20 m board on the wall face at eye height whose front box carries the
     PNG as a `texture` part,
  3. copies title/provenance/license/howto/prompt as the `gallery` block onto the exhibit
     element (-> Pset_Gallery, shown by every IFC viewer and as floating labels in web/).
     `element` may name an entry in the storey JSON, in a data/variants file (every variant
     file that holds the id is updated so `variant.py check` stays clean), or a product in
     data/products/ (the block goes into its geometry and is carried by every placement).
     With `element: null` the plaque itself carries the block.

The text is authored once, in data/gallery.json; everything else is derived.
"""
import json
import sys
from pathlib import Path

import pymupdf

sys.path.insert(0, str(Path(__file__).resolve().parent))
from house import HOUSE  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data'
PLAQUES = ROOT / 'assets' / 'plaques'
GALLERY = DATA / 'gallery.json'

W_PX, H_PX = 600, 400
BOARD_W, BOARD_H, BOARD_T = 0.30, 0.20, 0.02   # metres
EYE_Z = 1.5
BG, FG, MUTED, ACCENT = (0.11, 0.11, 0.13), (0.96, 0.95, 0.92), (0.66, 0.66, 0.68), (0.85, 0.55, 0.40)


def render(exhibit, path):
    doc = pymupdf.open()
    page = doc.new_page(width=W_PX, height=H_PX)
    page.draw_rect(page.rect, color=None, fill=BG)
    page.draw_rect(pymupdf.Rect(28, 28, 44, 44), color=None, fill=ACCENT)
    x0, x1 = 56, W_PX - 32
    y = 22
    y += fit_text(page, pymupdf.Rect(x0, y, x1, y + 80), exhibit['title'], 'hebo', 26, FG, min_size=16)
    y += 8
    y += fit_text(page, pymupdf.Rect(x0, y, x1, y + 90), exhibit['provenance'], 'helv', 12, MUTED, min_size=8)
    y += 2
    y += fit_text(page, pymupdf.Rect(x0, y, x1, y + 30), 'Licence: ' + exhibit['license'], 'helv', 12, MUTED, min_size=8)
    y += 8
    page.draw_line(pymupdf.Point(x0, y), pymupdf.Point(x1, y), color=(0.3, 0.3, 0.33), width=0.8)
    y += 10
    y += fit_text(page, pymupdf.Rect(x0, y, x1, y + 110), exhibit['howto'], 'helv', 12.5, FG, min_size=8)
    y += 10
    y += fit_text(page, pymupdf.Rect(x0, y, x1, y + 20), 'Ask your agent:', 'hebo', 12, ACCENT, min_size=10)
    y += 2
    fit_text(page, pymupdf.Rect(x0, y, x1, H_PX - 20), '"' + exhibit['prompt'] + '"', 'cour', 12.5, FG, min_size=8)
    path.parent.mkdir(parents=True, exist_ok=True)
    page.get_pixmap(dpi=72, alpha=False).save(path)
    doc.close()


def fit_text(page, rect, text, font, size, color, min_size):
    """Insert text, shrinking the font until it fits; returns the height used."""
    while size >= min_size:
        rest = page.insert_textbox(rect, text, fontname=font, fontsize=size, color=color, align=0)
        if rest >= 0:
            return rect.height - rest
        size -= 1
    raise ValueError(f'plaque text does not fit at {min_size} pt: {text[:40]}...')


def board_entry(exhibit, storey):
    """Plaque furniture entry: board on the wall face, textured front box."""
    key = exhibit['key'].replace('-', '_').upper()
    (ax, ay), (nx, ny) = exhibit['plaque']['at'], exhibit['plaque']['normal']
    z0, z1 = round(EYE_Z - BOARD_H / 2, 3), round(EYE_Z + BOARD_H / 2, 3)
    hw = BOARD_W / 2
    if nx:                                      # board on a wall running along y
        xs = sorted((ax, ax + nx * (BOARD_T - 0.005)))
        xf = sorted((ax + nx * (BOARD_T - 0.005), ax + nx * BOARD_T))
        back = [xs[0], ay - hw, z0, xs[1], ay + hw, z1]
        front = [xf[0], ay - hw, z0, xf[1], ay + hw, z1]
        u_axis = '+y' if nx > 0 else '-y'
    else:
        ys = sorted((ay, ay + ny * (BOARD_T - 0.005)))
        yf = sorted((ay + ny * (BOARD_T - 0.005), ay + ny * BOARD_T))
        back = [ax - hw, ys[0], z0, ax + hw, ys[1], z1]
        front = [ax - hw, yf[0], z0, ax + hw, yf[1], z1]
        u_axis = '-x' if ny > 0 else '+x'
    image = f'assets/plaques/{exhibit["key"]}.png'
    entry = {
        'id': f'GAL_PLAQUE_{key}',
        '_comment': 'Generated by src/gen_plaques.py from data/gallery.json; edit the text there.',
        'parts': [
            {'name': 'board', 'rgb': [0.11, 0.11, 0.13], 'boxes': [[round(v, 4) for v in back]]},
            {'name': 'face', 'texture': {'image': image, 'u_axis': u_axis, 'v_axis': '+z'}, 'boxes': [[round(v, 4) for v in front]]},
        ],
        'props': {
            'Product': f'Gallery plaque: {exhibit["title"]}',
            'Supplier': 'none (generated)',
            'SourceURL': 'data/gallery.json',
            'Dimensions': f'{round(BOARD_W * 100)} x {round(BOARD_T * 100)} x {round(BOARD_H * 100)} cm',
            'License': 'MIT (project data)',
            'Status': 'Exhibit',
            'PlaqueFor': exhibit['element'] if isinstance(exhibit['element'], str) else ', '.join(exhibit['element'] or ['(this plaque)']),
            'Texture': image,
        },
    }
    if exhibit['element'] is None:
        entry['gallery'] = gallery_block(exhibit)
    return entry


def gallery_block(exhibit):
    return {'Title': exhibit['title'], 'Provenance': exhibit['provenance'], 'License': exhibit['license'],
            'HowTo': exhibit['howto'], 'Prompt': exhibit['prompt']}


def upsert(entries, entry):
    """Replace the entry with the same id in place, else append. Returns True when changed."""
    for i, existing in enumerate(entries):
        if existing.get('id') == entry['id']:
            if existing == entry:
                return False
            entries[i] = entry
            return True
    entries.append(entry)
    return True


def set_gallery(doc, element_id, block):
    """Set `gallery` on the entry with element_id anywhere in a {section: [entries]} document."""
    changed = found = False
    for section, items in doc.items():
        if not isinstance(items, list):
            continue
        for item in items:
            if isinstance(item, dict) and item.get('id') == element_id:
                found = True
                if item.get('gallery') != block:
                    item['gallery'] = block
                    changed = True
    return found, changed


def apply(check_only=False):
    spec = json.loads(GALLERY.read_text())
    storey = spec.get('storey', HOUSE.default_code())
    plan_path = DATA / HOUSE.file[storey]
    plan = json.loads(plan_path.read_text())
    touched = {plan_path: False}
    docs = {plan_path: plan}

    def load(path):
        if path not in docs:
            docs[path] = json.loads(path.read_text())
            touched[path] = False
        return docs[path]

    for exhibit in spec['exhibits']:
        png = PLAQUES / f'{exhibit["key"]}.png'
        if not check_only:
            render(exhibit, png)
        if not png.is_file():
            raise FileNotFoundError(f'{png.relative_to(ROOT)} missing; run without --check')
        plan.setdefault('furniture', [])
        if upsert(plan['furniture'], board_entry(exhibit, storey)):
            touched[plan_path] = True
        targets = exhibit['element']
        if not targets:
            continue
        block = gallery_block(exhibit)
        for target in ([targets] if isinstance(targets, str) else targets):
            found = False
            for path in [plan_path, *sorted((DATA / 'variants').rglob('*.json')), *sorted((DATA / 'products').glob('*.json'))]:
                doc = load(path)
                if path.parent == DATA / 'products':
                    if doc.get('id') == target:
                        found = True
                        if doc['geometry'].get('gallery') != block:
                            doc['geometry']['gallery'] = block
                            touched[path] = True
                    continue
                hit, changed = set_gallery(doc, target, block)
                found |= hit
                touched[path] |= changed
            if not found:
                raise LookupError(f'{exhibit["key"]}: element {target!r} is not defined in the storey JSON, a variant file or a product')
    if check_only:
        stale = [p.relative_to(ROOT) for p, t in touched.items() if t]
        if stale:
            print('gen_plaques: data out of date in ' + ', '.join(map(str, stale)) + '; run uv run python src/gen_plaques.py')
            return 1
        print(f'gen_plaques: {len(spec["exhibits"])} plaques consistent')
        return 0
    from viewer_common import atomic_json
    for path, doc in docs.items():
        if touched[path]:
            atomic_json(path, doc)
            print(f'updated {path.relative_to(ROOT)}')
    print(f'gen_plaques: {len(spec["exhibits"])} plaques rendered into {PLAQUES.relative_to(ROOT)}/')
    return 0


if __name__ == '__main__':
    sys.exit(apply(check_only='--check' in sys.argv))
