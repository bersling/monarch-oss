def markslojd_soleil_pendant(cable=1.50):
    """Markslöjd Soleil 12-light pendant, gold (Lampenwelt.ch art. 6506272,
    Markslöjd 107752). Sputnik / sea-urchin: ~260 thin gold rods of nearly
    equal length radiate in all directions from a small central hub, forming a
    Ø 72 cm sphere; the 12 E14 candle bulbs sit on short rods inside the
    sphere at about 40 % radius. Canopy Ø 12 x 6 cm, transparent cable.
    `cable` = drop from the canopy underside to the sphere CENTRE.
    Origin: x/y centred, z_min = 0 at the lowest rod tip, canopy top at the top."""
    import math, random
    rnd = random.Random(6506272)
    V, F = [], []
    R = 0.36
    zc = R                                   # sphere centre
    # canopy
    z0 = zc + cable
    rings = [(z0, superellipse(0.06, 0.06, 0.0, 0.0, n=2.0, segs=24)),
             (z0 + 0.06, superellipse(0.06, 0.06, 0.0, 0.0, n=2.0, segs=24))]
    v, f = loft(rings); base = len(V)
    V += v; F += [(a_ + base, b_ + base, c_ + base) for a_, b_, c_ in f]
    cap(V, F, base, 24, z0, flip=True); cap(V, F, base + 24, 24, z0 + 0.06)
    box(V, F, -0.003, -0.003, zc, 0.003, 0.003, z0)                     # cable down to the hub
    box(V, F, -0.025, -0.025, zc - 0.025, 0.025, 0.025, zc + 0.025)     # hub
    n = 260
    golden = math.pi * (3 - math.sqrt(5))
    for i in range(n):                                                  # fibonacci sphere directions
        y = 1 - 2 * (i + 0.5) / n
        r = math.sqrt(1 - y * y)
        t = golden * i
        dx, dy, dz = r * math.cos(t), y, r * math.sin(t)
        L = R * rnd.uniform(0.82, 1.0)              # nearly all rods reach the sphere surface
        bar(V, F, (0.0, 0.0, zc), (dx * L, dy * L, zc + dz * L), 0.008, 0.008)
    for i in range(12):                                                 # bulbs on short rods, two rings
        a_ = 2 * math.pi * i / 12 + 0.2
        el = 0.45 if i % 2 == 0 else -0.35
        dx, dy, dz = math.cos(a_) * math.cos(el), math.sin(a_) * math.cos(el), math.sin(el)
        Lr = R * 0.38
        ex, ey, ez = dx * Lr, dy * Lr, zc + dz * Lr
        # socket + candle bulb continue along the rod direction (bulb Ø 3.5, 10 cm)
        box(V, F, ex - 0.012, ey - 0.012, ez - 0.012, ex + 0.012, ey + 0.012, ez + 0.012)
        bar(V, F, (ex, ey, ez), (ex + dx * 0.12, ey + dy * 0.12, ez + dz * 0.12), 0.035, 0.035)
    zmin = min(p_[2] for p_ in V)
    V = [(x, y, z - zmin) for x, y, z in V]
    write_obj(ASSETS / 'markslojd_soleil_pendant.obj', V, F)



