"""Generate procedural mesh assets (OBJ) for the model — curved geometry the
box/cylinder primitives can't express.

Usage: uv run python src/gen_assets.py     (writes into assets/)

Assets are authored in meters, origin conventions documented per asset.
Referenced from plan JSONs via {"mesh": "assets/<name>.obj", "at": [x,y,z],
"rotation_z": deg} on any furniture/sanitary entry (see build_model.py).
"""
import math
from pathlib import Path

ASSETS = Path(__file__).resolve().parent.parent / "assets"
ASSETS.mkdir(exist_ok=True)


def superellipse(rx, ry, cx, cy, n=2.4, segs=32):
    """Ring of points; n=2 ellipse, higher = squarish-round."""
    pts = []
    for i in range(segs):
        t = 2 * math.pi * i / segs
        c, s = math.cos(t), math.sin(t)
        x = cx + rx * math.copysign(abs(c) ** (2 / n), c)
        y = cy + ry * math.copysign(abs(s) ** (2 / n), s)
        pts.append((x, y))
    return pts


def loft(rings):
    """rings: list of (z, [(x,y)...]) same length -> verts, quads-as-tris."""
    verts, faces = [], []
    segs = len(rings[0][1])
    for z, ring in rings:
        for x, y in ring:
            verts.append((x, y, z))
    for r in range(len(rings) - 1):
        a, b = r * segs, (r + 1) * segs
        for i in range(segs):
            j = (i + 1) % segs
            faces.append((a + i, a + j, b + j))
            faces.append((a + i, b + j, b + i))
    return verts, faces


def cap(verts, faces, ring_start, segs, z, flip=False):
    """Fan cap over a ring (adds center vertex)."""
    cx = sum(verts[ring_start + i][0] for i in range(segs)) / segs
    cy = sum(verts[ring_start + i][1] for i in range(segs)) / segs
    verts.append((cx, cy, z))
    c = len(verts) - 1
    for i in range(segs):
        j = (i + 1) % segs
        tri = (ring_start + i, c, ring_start + j) if flip else (ring_start + i, ring_start + j, c)
        faces.append(tri)


def write_obj(path, verts, faces):
    with open(path, 'w') as f:
        f.write(f"# generated by gen_assets.py\n")
        for v in verts:
            f.write(f"v {v[0]:.4f} {v[1]:.4f} {v[2]:.4f}\n")
        for a, b, c in faces:
            f.write(f"f {a+1} {b+1} {c+1}\n")
    print(f"wrote {path} ({len(verts)} verts, {len(faces)} tris)")


def wc_wall_hung():
    """Wall-hung toilet. Origin: wall face y=0 (bowl extends +y), floor z=0,
    centered on x. Bowl width 0.37, reach 0.54, rim 0.41, closed lid 0.445."""
    segs = 32
    # (z, rx, ry) — back edge pinned to the wall: cy = ry
    profile = [
        (0.26, 0.115, 0.16),
        (0.285, 0.15, 0.215),
        (0.33, 0.175, 0.252),
        (0.38, 0.184, 0.268),
        (0.41, 0.185, 0.27),
        (0.425, 0.185, 0.27),   # seat edge
        (0.432, 0.17, 0.253),
        (0.445, 0.145, 0.225),  # lid top rim
    ]
    rings = [(z, superellipse(rx, ry, 0.0, ry, n=2.4, segs=segs)) for z, rx, ry in profile]
    verts, faces = loft(rings)
    cap(verts, faces, 0, segs, profile[0][0], flip=True)          # bottom
    cap(verts, faces, (len(profile) - 1) * segs, segs, profile[-1][0])  # lid
    write_obj(ASSETS / 'wc_wall_hung.obj', verts, faces)


def box(verts, faces, x0, y0, z0, x1, y1, z1):
    """Axis-aligned box appended to verts/faces (12 tris, outward normals)."""
    b = len(verts)
    verts += [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
              (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    q = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    for a, b_, c, d in q:
        faces += [(b + a, b + b_, b + c), (b + a, b + c, b + d)]


def velopa_bigroof_300():
    """Velopa BigRoof Typ 300 (shop.velopa.ch/produkt/bigroof-3-00m), configured as
    on the shop page 04.09.2026: feuerverzinkt, Seitenwand Acrylglas links,
    Rückwand Acrylglas, Multibike Standard 6 Velos.
    Datasheet: width 300 (posts) / 310 (roof), feet depth 140, roof depth 210,
    clear height 187, total 192, low edge 125.
    Profile (owner, 05.09.2026): the TALL side is the open front (1.92), the
    roof is one continuous arc that rounds down towards the back, where the
    lower rear wall (1.25) stands on outward-leaning rear struts.
    Origin: x/y centred on the 300 x 140 foot print, z_min = 0.
    -y = open front (bikes roll in), +y = rear wall, -x = side wall ("links"
    seen from the front). Two files: frame/roof + acrylic walls."""
    import math
    V, F = [], []
    W = 3.00
    yf, yb = -0.70, 0.70                  # front posts (vertical), rear feet
    zr, zl = 1.92, 1.25                   # tall front, low rear edge
    y0, y1 = -0.85, 1.25                  # roof: 0.15 front overhang, rear edge over the leaning struts (2.10 deep)
    dy, dz = y1 - y0, zr - zl
    R = (dy * dy + dz * dz) / (2 * dz)     # horizontal tangent at the front, down to (y1, zl)
    zc = zr - R
    amax = math.asin(dy / R)
    ang = [i * amax / 14 for i in range(15)]
    arc = [(y0 + R * math.sin(t), zc + R * math.cos(t)) for t in ang]
    for sx in (-1, 1):
        x = sx * W / 2
        box(V, F, x - 0.03, yf - 0.03, 0.0, x + 0.03, yf + 0.03, zr - 0.05)   # tall front post
        bar(V, F, (x, yb, 0.0), (x, y1, zl - 0.02), 0.06, 0.06)              # leaning rear strut
        bar(V, F, (x, yb, 0.0), (x, yf, zr * 0.5), 0.04, 0.04)               # diagonal brace
        for (ya, za), (yb_, zb) in zip(arc, arc[1:]):                        # arc rib
            bar(V, F, (x, ya, za - 0.04), (x, yb_, zb - 0.04), 0.05, 0.05)
    box(V, F, -W / 2, yf - 0.03, zr - 0.10, W / 2, yf + 0.03, zr - 0.05)     # front top rail
    box(V, F, -W / 2, yf - 0.02, 0.0, W / 2, yf + 0.02, 0.05)                # front ground rail
    box(V, F, -W / 2, yb - 0.02, 0.10, W / 2, yb + 0.02, 0.16)               # rear bottom rail
    for (ya, za), (yb_, zb) in zip(arc, arc[1:]):                            # roof sheet 3.10 wide
        bb = len(V)
        V += [(-1.55, ya, za - 0.04), (1.55, ya, za - 0.04), (1.55, yb_, zb - 0.04), (-1.55, yb_, zb - 0.04),
              (-1.55, ya, za), (1.55, ya, za), (1.55, yb_, zb), (-1.55, yb_, zb)]
        for a_, b_, c, d in [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]:
            F += [(bb + a_, bb + b_, bb + c), (bb + a_, bb + c, bb + d)]
    for i in range(6):                                                       # Multibike Standard 6
        x = -1.25 + i * 0.50
        for sx in (-1, 1):
            bar(V, F, (x + sx * 0.03, yf + 0.15, 0.0), (x + sx * 0.03, yf + 0.40, 0.35), 0.02, 0.02)
        box(V, F, x - 0.04, yf + 0.38, 0.33, x + 0.04, yf + 0.42, 0.37)
    write_obj(ASSETS / 'velopa_bigroof_300.obj', V, F)
    # acrylic: rear wall in the plane of the leaning struts + left side wall following the profile
    G, GF = [], []
    bb = len(G)
    G += [(-W / 2 + 0.04, yb, 0.16), (W / 2 - 0.04, yb, 0.16), (W / 2 - 0.04, y1 - 0.02, zl - 0.08), (-W / 2 + 0.04, y1 - 0.02, zl - 0.08)]
    G += [(x_, y_ - 0.01, z_) for x_, y_, z_ in G[bb:bb + 4]]
    GF += [(bb, bb + 1, bb + 2), (bb, bb + 2, bb + 3), (bb + 4, bb + 6, bb + 5), (bb + 4, bb + 7, bb + 6)]
    x = -W / 2 + 0.035
    prof = [(yf + 0.03, 0.05), (yb, 0.05)] + [(y, z - 0.06) for y, z in reversed(arc)]
    bb = len(G); n = len(prof)
    G += [(x, y, z) for y, z in prof] + [(x + 0.01, y, z) for y, z in prof]
    for i in range(1, n - 1):
        GF.append((bb, bb + i, bb + i + 1)); GF.append((bb + n, bb + n + i + 1, bb + n + i))
    write_obj(ASSETS / 'velopa_bigroof_300_glass.obj', G, GF)



def bush_blob():
    """Generic shrub: squashed ellipsoid, 1.00 m diameter, 1.20 m high, x/y
    centred, z_min = 0. Scale with the per-object "scale" key to the crown
    diameter read off the plan (height scales along)."""
    import math
    segs, rings = 20, 9
    prof = []
    for i in range(1, rings):
        t = i / rings
        z = 1.20 * t
        r = 0.50 * math.sin(math.pi * t) ** 0.7
        prof.append((z, superellipse(r, r, 0.0, 0.0, n=2.0, segs=segs)))
    verts, faces = loft(prof)
    cap(verts, faces, 0, segs, prof[0][0], flip=True)
    cap(verts, faces, (len(prof) - 1) * segs, segs, prof[-1][0])
    write_obj(ASSETS / 'bush_blob.obj', verts, faces)


def bar(verts, faces, p0, p1, w, h):
    """Slanted rectangular bar between p0 and p1 (w wide across, h thick along the local up)."""
    import math
    (x0, y0, z0), (x1, y1, z1) = p0, p1
    dx, dy, dz = x1 - x0, y1 - y0, z1 - z0
    L = math.sqrt(dx * dx + dy * dy + dz * dz)
    ax = (dx / L, dy / L, dz / L)
    # side vector: horizontal, perpendicular to the axis
    hx, hy = -ax[1], ax[0]
    hl = math.hypot(hx, hy) or 1.0
    side = (hx / hl, hy / hl, 0.0)
    up = (ax[1] * side[2] - ax[2] * side[1], ax[2] * side[0] - ax[0] * side[2], ax[0] * side[1] - ax[1] * side[0])
    b = len(verts)
    for (px, py, pz) in (p0, p1):
        for sw, su in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
            verts.append((px + side[0] * sw * w / 2 + up[0] * su * h / 2,
                          py + side[1] * sw * w / 2 + up[1] * su * h / 2,
                          pz + side[2] * sw * w / 2 + up[2] * su * h / 2))
    q = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    for a, b_, c, d in q:
        faces += [(b + a, b + b_, b + c), (b + a, b + c, b + d)]


